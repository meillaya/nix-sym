#include "gdb.hpp"

#include <algorithm>
#include <fcntl.h>
#include <unistd.h>

#include <filesystem>
#include <set>
#include <sstream>
#include <string>
#include <vector>

namespace nix_sym {
namespace {

bool safe_path(const std::string& path) {
  return !path.empty() && path.find('\n') == std::string::npos &&
         path.find('\r') == std::string::npos && path.find(' ') == std::string::npos;
}

} // namespace

std::string render_gdb_init(const Backtrace& backtrace, const std::string& core_path,
                            const std::vector<SourceMapping>& mappings, bool live) {
  std::ostringstream out;
  out << "# Generated by nix-sym 0.3.0\n";
  out << "# Usage: gdb -x this-file\n";
  out << "set pagination off\n";
  out << "set confirm off\n";
  out << "set debuginfod enabled off\n";

  std::set<std::string> debug_dirs;
  for (const auto& module : backtrace.modules) {
    if (!module.debug_output.empty()) {
      std::string directory = module.debug_output + "/lib/debug";
      if (safe_path(directory) && std::filesystem::is_directory(directory)) {
        debug_dirs.insert(directory);
      }
    }
  }
  if (!debug_dirs.empty()) {
    out << "set debug-file-directory";
    bool first = true;
    for (const auto& directory : debug_dirs) {
      out << (first ? " " : ":") << directory;
      first = false;
    }
    out << "\n";
  } else {
    out << "# no debug outputs were resolved\n";
  }

  std::set<std::string> seen;
  for (const auto& mapping : mappings) {
    if (mapping.resolved_root.empty() || mapping.root.empty()) {
      continue;
    }
    std::string from = mapping.comp_dir.empty() ? "/build/" + mapping.root : mapping.comp_dir;
    if (!safe_path(from) || !safe_path(mapping.resolved_root)) {
      out << "# skipped source mapping with whitespace: " << mapping.root << "\n";
      continue;
    }
    if (!seen.insert(from + "\n" + mapping.resolved_root).second) {
      continue;
    }
    out << "set substitute-path " << from << " " << mapping.resolved_root << "\n";
    if (mapping.status != "resolved") {
      out << "# source mapping is " << mapping.status << ": " << from << "\n";
    }
  }

  std::string executable;
  if (!backtrace.threads.empty() && !backtrace.threads.front().frames.empty()) {
    const std::string& candidate = backtrace.threads.front().frames.back().module_path;
    if (!candidate.empty() && safe_path(candidate)) {
      std::error_code ec;
      if (std::filesystem::is_regular_file(candidate, ec) &&
          ::access(candidate.c_str(), X_OK) == 0) {
        executable = candidate;
      }
    }
  }
  if (executable.empty()) {
    for (const auto& module : backtrace.modules) {
      if (module.path.empty() || !safe_path(module.path)) {
        continue;
      }
      std::error_code ec;
      if (std::filesystem::is_regular_file(module.path, ec) &&
          ::access(module.path.c_str(), X_OK) == 0) {
        executable = module.path;
        break;
      }
    }
  }
  if (!executable.empty()) {
    out << "file " << executable << "\n";
  }

  if (live) {
    if (backtrace.core.pid > 0) {
      out << "attach " << backtrace.core.pid << "\n";
    } else {
      out << "# live process id is unknown; run attach manually\n";
    }
  } else {
    std::error_code ec;
    std::filesystem::path absolute_core = std::filesystem::absolute(core_path, ec);
    std::string core_string = ec ? core_path : absolute_core.string();
    if (safe_path(core_string)) {
      out << "core-file " << core_string << "\n";
    } else {
      out << "# core path contains whitespace; run core-file manually: " << core_string << "\n";
    }
  }
  out << "# nix-sym: " << backtrace.modules.size() << " modules, " << backtrace.threads.size()
      << " threads\n";
  return out.str();
}

} // namespace nix_sym
